CREATE TABLE team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lfsworld_id BIGINT UNIQUE,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    tag TEXT,
    website_url TEXT,
    description TEXT,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(tags) = 'array' AND tags <@ '["race", "drift", "drag"]'::jsonb),
    accepts_applications BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disbanded')),
    lfsworld_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE team_member (
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES player(id),
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
    PRIMARY KEY (team_id, player_id)
);
CREATE INDEX team_member_player ON team_member (player_id, team_id);
