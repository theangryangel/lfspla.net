-- Preserve existing object locations. Files are relocated separately by the operator.
CREATE TABLE attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key TEXT NOT NULL UNIQUE CHECK (btrim(object_key) <> ''),
    sha256 TEXT CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0),
    media_type TEXT NOT NULL CHECK (btrim(media_type) <> ''),
    extension TEXT NOT NULL CHECK (extension ~ '^[a-z0-9]+$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO attachment (object_key, media_type, extension)
SELECT object_key, min(media_type), min(extension)
FROM (
    SELECT spr_object_key AS object_key, 'application/octet-stream' AS media_type, 'spr' AS extension
    FROM hotlap WHERE spr_object_key IS NOT NULL
    UNION ALL
    SELECT raf_object_key, 'application/octet-stream', 'raf'
    FROM hotlap WHERE raf_object_key IS NOT NULL
    UNION ALL
    SELECT image_object_key, image_content_type,
        CASE image_content_type
            WHEN 'image/png' THEN 'png'
            WHEN 'image/jpeg' THEN 'jpg'
            WHEN 'image/webp' THEN 'webp'
            WHEN 'image/gif' THEN 'gif'
            WHEN 'image/avif' THEN 'avif'
            WHEN 'image/svg+xml' THEN 'svg'
            ELSE 'bin'
        END
    FROM vehicle WHERE image_object_key IS NOT NULL
) AS existing
GROUP BY object_key;

ALTER TABLE hotlap
    ADD COLUMN spr_attachment_id BIGINT REFERENCES attachment(id) ON DELETE RESTRICT,
    ADD COLUMN raf_attachment_id BIGINT REFERENCES attachment(id) ON DELETE RESTRICT;
ALTER TABLE vehicle
    ADD COLUMN image_attachment_id BIGINT REFERENCES attachment(id) ON DELETE RESTRICT;
UPDATE hotlap SET spr_attachment_id = attachment.id
FROM attachment WHERE attachment.object_key = hotlap.spr_object_key;
UPDATE hotlap SET raf_attachment_id = attachment.id
FROM attachment WHERE attachment.object_key = hotlap.raf_object_key;
UPDATE vehicle SET image_attachment_id = attachment.id
FROM attachment WHERE attachment.object_key = vehicle.image_object_key;

ALTER TABLE hotlap
    DROP CONSTRAINT hotlap_replay_provenance_check,
    DROP COLUMN spr_object_key,
    DROP COLUMN raf_object_key,
    ADD CONSTRAINT hotlap_replay_provenance_check CHECK (
        (source = 'upload' AND spr_attachment_id IS NOT NULL AND fingerprint ~ '^[0-9a-f]{64}$')
        OR (source = 'lfsworld_v1' AND spr_attachment_id IS NULL
            AND fingerprint ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}:[1-9][0-9]*$')
        OR (source = 'demo' AND spr_attachment_id IS NULL AND original_filename IS NULL
            AND fingerprint LIKE 'demo:%')
    );
ALTER TABLE vehicle
    DROP CONSTRAINT vehicle_image_metadata_check,
    DROP COLUMN image_object_key,
    DROP COLUMN image_content_type,
    ADD CONSTRAINT vehicle_image_metadata_check CHECK (
        (image_attachment_id IS NULL AND image_fetched_at IS NULL)
        OR (image_attachment_id IS NOT NULL AND image_fetched_at IS NOT NULL)
    );
CREATE INDEX hotlap_spr_attachment_idx ON hotlap (spr_attachment_id) WHERE spr_attachment_id IS NOT NULL;
CREATE INDEX hotlap_raf_attachment_idx ON hotlap (raf_attachment_id) WHERE raf_attachment_id IS NOT NULL;
CREATE INDEX vehicle_image_attachment_idx ON vehicle (image_attachment_id) WHERE image_attachment_id IS NOT NULL;
