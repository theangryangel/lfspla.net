CREATE TABLE league (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    description TEXT,
    website_url TEXT,
    forum_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE season (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id BIGINT NOT NULL REFERENCES league(id),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, league_id)
);
CREATE INDEX season_league ON season (league_id);

CREATE TABLE event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id BIGINT NOT NULL REFERENCES league(id),
    season_id BIGINT,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT,
    starts_at TIMESTAMPTZ NOT NULL,
    details_url TEXT,
    signup_url TEXT,
    track_label TEXT,
    cars_label TEXT,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (season_id, league_id) REFERENCES season(id, league_id)
);
CREATE INDEX event_upcoming ON event (starts_at, id) WHERE NOT hidden;
CREATE INDEX event_league ON event (league_id, starts_at, id);
CREATE INDEX event_season ON event (season_id, starts_at, id);

-- Parent-qualified external IDs avoid assuming global upstream ID uniqueness.
-- Examples: league 432, season 432/1347, event 432/1347/6696.
CREATE TABLE league_source (
    league_id BIGINT NOT NULL REFERENCES league(id) ON DELETE CASCADE,
    source TEXT NOT NULL CHECK (source = 'lfs_net'),
    external_id TEXT NOT NULL CHECK (length(external_id) > 0),
    source_url TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    last_synced_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (source, external_id),
    UNIQUE (league_id, source)
);
CREATE TABLE season_source (
    season_id BIGINT NOT NULL REFERENCES season(id) ON DELETE CASCADE,
    source TEXT NOT NULL CHECK (source = 'lfs_net'),
    external_id TEXT NOT NULL CHECK (length(external_id) > 0),
    source_url TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    last_synced_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (source, external_id),
    UNIQUE (season_id, source)
);
CREATE TABLE event_source (
    event_id BIGINT NOT NULL REFERENCES event(id) ON DELETE CASCADE,
    source TEXT NOT NULL CHECK (source = 'lfs_net'),
    external_id TEXT NOT NULL CHECK (length(external_id) > 0),
    source_url TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    last_synced_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (source, external_id),
    UNIQUE (event_id, source)
);
